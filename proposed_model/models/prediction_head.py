"""
models/prediction_head.py

Prediction Head

Converts latent node representations generated by
GraphWaveNet into multi-step traffic forecasts.

Input
-----
(B, T, N, D)

Output
------
(B, H, N)

where

T = History Length
H = Prediction Horizon
D = Embedding Dimension
"""

from __future__ import annotations

import torch
import torch.nn as nn

from configs.config import (
    EMBEDDING_DIM,
    HISTORY_LENGTH,
    PREDICTION_HORIZON,
)


class PredictionHead(nn.Module):
    """
    Multi-step Forecast Head.

    Input
    -----
    (B, T, N, D)

    Output
    ------
    (B, H, N)
    """

    def __init__(
        self,
        history_length: int = HISTORY_LENGTH,
        embedding_dim: int = EMBEDDING_DIM,
        prediction_horizon: int = PREDICTION_HORIZON,
        dropout: float = 0.1,
    ):
        super().__init__()

        self.history_length = history_length
        self.embedding_dim = embedding_dim
        self.prediction_horizon = prediction_horizon

        # --------------------------------------------------
        # Feature Refinement
        # D -> D
        # --------------------------------------------------

        self.feature_projection = nn.Linear(
            embedding_dim,
            embedding_dim,
        )

        self.activation = nn.GELU()

        self.dropout = nn.Dropout(
            dropout,
        )

        # --------------------------------------------------
        # Temporal Compression
        #
        # (T,D)
        # ->
        # D
        # --------------------------------------------------

        self.temporal_projection = nn.Linear(
            history_length,
            1,
        )

        # --------------------------------------------------
        # Forecast Projection
        #
        # D
        # ->
        # H
        # --------------------------------------------------

        self.output_projection = nn.Linear(
            embedding_dim,
            prediction_horizon,
        )

        self._initialize_weights()

#
    def _initialize_weights(self):
        """
            Xavier initialization for all Linear layers.
        """

        for module in self.modules():

            if isinstance(module, nn.Linear):

                nn.init.xavier_uniform_(
                    module.weight
                )

                if module.bias is not None:

                    nn.init.zeros_(
                        module.bias
                    )


    def forward(
        self,
        x: torch.Tensor,
    ) -> torch.Tensor:

        if x.ndim != 4:

            raise ValueError(
                "PredictionHead expects input shape (B,T,N,D)"
            )


        _, history, _, embedding_dim = x.shape


        if history != self.history_length:

            raise ValueError(
                f"Expected history length "
                f"{self.history_length}, "
                f"received {history}"
            )


        if embedding_dim != self.embedding_dim:

            raise ValueError(
                f"Expected embedding dimension "
                f"{self.embedding_dim}, "
                f"received {embedding_dim}"
            )


        # Feature refinement

        x = self.feature_projection(x)

        x = self.activation(x)

        x = self.dropout(x)


        # Temporal compression

        x = x.permute(
            0,
            3,
            2,
            1,
        )


        x = self.temporal_projection(x)

        x = self.activation(x)

        x = x.squeeze(-1)


        # (B,D,N) -> (B,N,D)

        x = x.permute(
            0,
            2,
            1,
        )


        # D -> H

        prediction = self.output_projection(x)


        # (B,N,H) -> (B,H,N)

        prediction = prediction.permute(
            0,
            2,
            1,
        )


        if torch.isnan(prediction).any():

            raise RuntimeError(
                "NaN values detected in PredictionHead output."
            )


        return prediction

